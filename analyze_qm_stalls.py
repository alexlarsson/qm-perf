#!/usr/bin/env python3
"""Inventory slow operations, service context, and kernel differences.

Requires service-outliers.csv generated by analyze_qm_services.py. Timings are
exported seconds and reconstructed kernel-relative seconds (export - metadata
offset). Neither a slow-operation interval nor a watchdog age is an exact
measurement of when a physical CPU stall began.
"""

import csv
import json
import re
from collections import Counter, defaultdict
from pathlib import Path

OUT = Path("qm-analysis")


def csv_write(name, rows):
    with (OUT / name).open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def normalize_kernel(message):
    text = message.removeprefix("kernel: ")
    text = re.sub(r"audit\([^)]*\)", "audit(TIME:SEQ)", text)
    text = re.sub(r"\bpid=\d+", "pid=PID", text)
    if "setting system clock to " in text:
        text = re.sub(r"to .* UTC \(\d+\)", "to DATE UTC (EPOCH)", text)
    text = re.sub(r"\b[0-9a-fA-F]{8}-[0-9a-fA-F-]{27,}\b", "UUID", text)
    text = re.sub(r"\b0x[0-9a-fA-F]+\b", "HEX", text)
    text = re.sub(r"\bffff[0-9a-fA-F]{12}\b", "ADDR", text)
    if text.startswith("Memory: "):
        text = re.sub(r"Memory: \d+K/", "Memory: AVAILABLE_K/", text)
        text = re.sub(r"\d+K reserved", "RESERVED_K reserved", text)
    return text


def service_context(boot, anchor):
    states = {}
    transitions = []
    completion_actions = {}
    for event in boot["journal"]:
        match = re.match(r"^systemd\[1\]: (Started|Finished) (\S+?\.service)(?: - |\.)", event["name"])
        if match:
            completion_actions[match[2]] = match[1]
    for event in sorted(boot["journal"], key=lambda e: e["activating"]):
        timestamp = event["activating"] / 1e6 - boot["offset"]
        if timestamp <= 0:
            continue  # Includes synthetic zero-time journal records.
        name = event["name"]
        match = re.match(r"^systemd\[1\]: (Starting|Started|Finished|Stopping|Stopped|Failed to start) (\S+?\.service)(?: - |\.\.\.|\.)", name)
        deactivate = re.match(r"^systemd\[1\]: (\S+?\.service): (?:Deactivated successfully|Failed with result)", name)
        if match:
            action, unit = match.groups()
            transitions.append((timestamp, unit, action))
            if timestamp <= anchor:
                states[unit] = action
        elif deactivate and timestamp <= anchor:
            states[deactivate[1]] = "inactive"
    # Some completion journal entries have synthetic zero timestamps. Recover
    # completed startups from the independent unit interval where possible.
    for event in boot["data"]["boot_logs"]:
        if event["source"] != "saplot" or states.get(event["name"]) != "Starting" or event["time"] <= 0:
            continue
        start = event["activating"] / 1e6 - boot["offset"]
        end = start + event["time"] / 1e6
        last_start = max((t for t, unit, action in transitions if unit == event["name"] and action == "Starting" and t <= anchor), default=None)
        if last_start is not None and abs(start - last_start) < 0.1 and end <= anchor:
            states[event["name"]] = completion_actions.get(event["name"], "completed")
    starting = {unit for unit, state in states.items() if state == "Starting"}
    # The initrd journal is buffered. Unit activation spans supply its context.
    initrd_end = next(e["activated"] / 1e6 - boot["offset"] for e in boot["data"]["boot_logs"] if e["source"] == "systemd-dbus" and e["name"] == "InitRD")
    if anchor < initrd_end:
        for event in boot["data"]["boot_logs"]:
            if event["source"] != "saplot" or not event["name"].endswith(".service"):
                continue
            start = event["activating"] / 1e6 - boot["offset"]
            finish = start + event["time"] / 1e6
            if start <= anchor < finish:
                starting.add(event["name"])
    active = sorted(unit for unit, state in states.items() if state == "Started")
    stopping = sorted(unit for unit, state in states.items() if state == "Stopping")
    nearby = [f"{timestamp:.3f} {action} {unit}" for timestamp, unit, action in transitions if abs(timestamp - anchor) <= 1]
    return "; ".join(sorted(starting)), "; ".join(active), "; ".join(stopping), " | ".join(nearby)


def main():
    OUT.mkdir(exist_ok=True)
    boots = {}
    for run in (1, 2, 3):
        path = Path(f"qm-run-{run}.json")
        for index, data in enumerate(json.loads(path.read_text())[0]["boot_time"]):
            assert data["metadata"]["cntvct_offset_us"] == data["metadata"]["wall_clock_offset_us"]
            boots[(run, index)] = {
                "data": data,
                "offset": data["metadata"]["cntvct_offset_us"] / 1e6,
                "journal": [e for e in data["boot_logs"] if e["source"] == "journalctl"],
            }
    events = []

    def add(key, category, description, start_export, end_export=None, severity="long", note="", age=None):
        boot = boots[key]
        start = start_export - boot["offset"]
        end = end_export - boot["offset"] if end_export is not None else None
        anchor = start - age if age is not None else start
        starting, active, stopping, nearby = service_context(boot, anchor + 0.001)
        events.append({
            "run": key[0], "boot_index": key[1], "category": category,
            "description": description, "severity": severity,
            "start_kernel_s": start, "end_kernel_s": end,
            "start_export_s": start_export, "end_export_s": end_export,
            "duration_s": end_export - start_export if end_export is not None else None,
            "context_anchor_kernel_s": anchor,
            "starting_at_anchor": starting, "nominally_started_at_anchor": active,
            "stopping_at_anchor": stopping, "near_anchor_service_events": nearby,
            "note": note,
        })

    for row in csv.DictReader((OUT / "service-outliers.csv").open()):
        key = (int(re.search(r"run-(\d+)", row["file"])[1]), int(row["boot_index"]))
        start, duration = float(row["activating_s"]), float(row["duration_s"])
        add(key, "service", row["service"], start, start + duration,
            severity="long" if duration >= 20 else "moderate",
            note="Activation interval; onset unknown. End computed as activating + duration; exported activated may be stale after restarts.")

    signatures = defaultdict(set)
    examples = {}
    findings = []
    total_kernel = 0
    diagnostic_patterns = {
        "soft_lockup": r"BUG: soft lockup", "kernel_WARNING": r"WARNING:",
        "rcu_stall": r"rcu.*(?:stall|detected stalls)",
        "hung_task": r"blocked for more than|hung_task:",
        "oops_panic": r"Oops:|Kernel panic|Unable to handle kernel",
        "nic_watchdog": r"NETDEV WATCHDOG",
        "storage_io_error": r"I/O error|Buffer I/O|EXT4-fs error|mmc.*(?:error|timeout|timed out)",
        "clocksource_unstable": r"clocksource.*(?:unstable|watchdog.*fail|time.*jump)",
    }
    diagnostic_counts = Counter({name: 0 for name in diagnostic_patterns})
    for key, boot in boots.items():
        journal = boot["journal"]
        starts = [i for i, e in enumerate(journal) if e["name"] == "systemd[1]: Starting qm.service..."]
        first_attempt = journal[starts[0]: starts[1] if len(starts) > 1 else len(journal)]
        timeout = next((e for e in first_attempt if "qm.service: start operation timed out." in e["name"]), None)
        if timeout:
            add(key, "qm_timeout", "qm.service initial attempt", first_attempt[0]["activating"] / 1e6,
                timeout["activating"] / 1e6, note="Censored by configured startup timeout; not a measured natural stall duration.")
        for event in journal:
            name, export = event["name"], event["activating"] / 1e6
            if "Accepted publickey" in name:
                pid = re.match(r"sshd-session\[(\d+)\]", name)[1]
                pam = next((e for e in journal if e["name"].startswith(f"sshd-session[{pid}]: pam_unix(sshd:session): session opened")), None)
                if pam and (pam["activating"] - event["activating"]) > 10e6:
                    duration = (pam["activating"] - event["activating"]) / 1e6
                    add(key, "ssh_session", f"SSH PID {pid}: accepted key to PAM session", export, pam["activating"] / 1e6,
                        severity="long" if duration >= 20 else "moderate", note="Host session-opening interval; not TCP connection establishment or exact lockup onset.")
            if "Forward time jump detected!" in name:
                add(key, "clock_jump", "chronyd forward time-jump report", export,
                    severity="signal", note="Report time only; clock change/earlier stall onset not established.")
            if not name.startswith("kernel: "):
                continue
            total_kernel += 1
            for pattern_name, pattern in diagnostic_patterns.items():
                diagnostic_counts[pattern_name] += bool(re.search(pattern, name, re.I))
            normalized = normalize_kernel(name)
            signatures[normalized].add(key)
            examples.setdefault(normalized, name)
            kind = None
            lockup = re.search(r"BUG: soft lockup - CPU#(\d+) stuck for (\d+)s", name)
            if lockup:
                kind = "soft_lockup"
                age = int(lockup[2])
                add(key, "soft_lockup", f"CPU {lockup[1]} watchdog report, age {age}s", export,
                    severity="signal", age=age,
                    note=f"Detection time. Context uses report minus printed age = {export - boot['offset'] - age:.3f}s; heuristic last-watchdog-progress reference, not precise onset.")
            elif "hrtimer: interrupt took" in name:
                kind = "hrtimer_latency"
                add(key, "hrtimer_latency", name.removeprefix("kernel: "), export, severity="minor", note="Single 7.799 microsecond timer-handler diagnostic; not a seconds-long lockup.")
            elif any(fragment in name for fragment in ["POR issue detected", "Power loss detected", "hctosys: unable"]):
                kind = "rtc_invalid"
            elif "audit: type=1130" in name:
                kind = "audit_success"
            elif "veth0 (unregistering)" in name:
                kind = "veth_cleanup"
            if kind:
                findings.append({"run": key[0], "boot_index": key[1], "kind": kind,
                    "kernel_s": export - boot["offset"], "export_s": export, "message": name})
        ptp = next(e for e in journal if "s32-dwmac " in e["name"] and "end0: registered PTP clock" in e["name"])
        link = next(e for e in journal if "s32-dwmac " in e["name"] and "end0: configuring for fixed/rgmii-id" in e["name"])
        if link["activating"] - ptp["activating"] > 1e6:
            add(key, "nic_bringup", "NIC PTP registration to fixed-link configuration", ptp["activating"] / 1e6,
                link["activating"] / 1e6, note="Bracket between driver milestones, not proof which function stopped executing.")

    events.sort(key=lambda e: (e["run"], e["boot_index"], e["start_kernel_s"], e["category"]))
    csv_write("stall-events.csv", events)
    csv_write("kernel-findings.csv", findings)
    sigrows = [{"boot_count": len(keys), "signature": signature, "boots": "; ".join(f"{r}/{b}" for r, b in sorted(keys)), "example": examples[signature]} for signature, keys in signatures.items()]
    sigrows.sort(key=lambda row: (row["boot_count"], row["signature"]))
    csv_write("kernel-signatures.csv", sigrows)
    by_boot = defaultdict(list)
    for event in events:
        by_boot[(event["run"], event["boot_index"])].append(event)
    inventory, contexts = [], []
    for key, subset in by_boot.items():
        boot = boots[key]
        rtc = any("Power loss detected" in event["name"] for event in boot["journal"])
        inventory.append({"run": key[0], "boot_index": key[1], "rtc_invalid": rtc,
            "categories": "; ".join(sorted({event["category"] for event in subset})),
            "events": " | ".join(f"{event['start_kernel_s']:.3f}" + (f"–{event['end_kernel_s']:.3f}" if event['end_kernel_s'] is not None else "") + f" {event['description']}" for event in subset)})
        text = [f"RUN {key[0]} BOOT {key[1]}; offset {boot['offset']:.6f}s; RTC invalid: {rtc}"]
        for event in subset:
            text += ["", f"{event['category']}: {event['description']}",
                f"  kernel interval/report: {event['start_kernel_s']:.6f} -> {event['end_kernel_s']}",
                f"  context anchor: {event['context_anchor_kernel_s']:.6f}",
                f"  starting: {event['starting_at_anchor'] or '(none observed)'}",
                f"  nominally started: {event['nominally_started_at_anchor'] or '(none observed)'}",
                f"  stopping: {event['stopping_at_anchor'] or '(none observed)'}",
                f"  nearby unit transitions: {event['near_anchor_service_events'] or '(none observed)'}",
                f"  {event['note']}"]
        text += ["", "Nearby evidence (kernel-relative seconds; source journal order preserved):"]
        anchors = [value for event in subset for value in (event["start_kernel_s"], event["end_kernel_s"], event["context_anchor_kernel_s"]) if value is not None]
        for entry in boot["journal"]:
            time = entry["activating"] / 1e6 - boot["offset"]
            name = entry["name"]
            if any(abs(time - anchor) < 2 for anchor in anchors) and "Configuration file " not in name:
                text.append(f"{time:10.6f}  {name}")
        contexts.append("\n".join(text))
    csv_write("stall-boots.csv", inventory)
    (OUT / "stall-context.txt").write_text("\n\n".join(contexts) + "\n")
    inventory_lines = ["# Complete observation inventory", "",
        "Times are reconstructed seconds since kernel start. Intervals are operation bounds, not exact stall onset. Points are report times. See stall-report.md for interpretation and stall-timeline.html for expandable service context.", "",
        "| Run/index | Observation | Interval/report (s) | Context anchor (s) | Services starting at anchor |",
        "| --- | --- | --- | --- | --- |"]
    for event in events:
        span = f"{event['start_kernel_s']:.3f}" + (f"–{event['end_kernel_s']:.3f}" if event['end_kernel_s'] is not None else " (report)")
        inventory_lines.append(f"| {event['run']}/{event['boot_index']} | {event['description']} | {span} | {event['context_anchor_kernel_s']:.3f} | {event['starting_at_anchor'] or 'None observed'} |")
    (OUT / "stall-inventory.md").write_text("\n".join(inventory_lines) + "\n")

    from render_qm_timeline import render_report

    render_report(OUT, boots, events, by_boot)

    severe_keys = {(e["run"], e["boot_index"]) for e in events if e["severity"] in ("long", "signal")}
    rtc_keys = {key for key, boot in boots.items() if any("Power loss detected" in e["name"] for e in boot["journal"])}
    summary = {"boot_count": len(boots), "event_count": len(events), "candidate_boot_count": len(by_boot),
        "long_or_signal_boot_count": len(severe_keys), "event_categories": dict(Counter(e["category"] for e in events)),
        "kernel_message_count": total_kernel, "normalized_kernel_signature_count": len(signatures),
        "kernel_diagnostic_counts": dict(diagnostic_counts),
        "rtc_invalid_boot_count": len(rtc_keys), "rtc_invalid_and_long_or_signal": sorted(rtc_keys & severe_keys),
        "all_offset_fields_match": True}
    (OUT / "stall-summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary, indent=2))


if __name__ == "__main__":
    main()
